const t = (col: number, row: 'a' | 'b' | 'c' | 'd' | 'e' | 'f' | 'g' | 'h' | 'i' | 'j') =>
  ({
    kind: 'terminal' as const,
    strip: (['a', 'b', 'c', 'd', 'e'] as string[]).includes(row) ? 'upper' as const : 'lower' as const,
    col,
    row,
  });

const rail = (railId: 'top+' | 'top-' | 'bot+' | 'bot-', col: number) =>
  ({ kind: 'rail' as const, rail: railId, col });

